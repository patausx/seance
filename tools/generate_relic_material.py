#!/usr/bin/env python3
"""Bake renderer-only four-mass detail on the unchanged production control mesh.

Each control triangle is subdivided four ways per edge. XY is barycentric in
that triangle (the 32-sided control silhouette stays authoritative). Z samples
the original av_visual height equation at those immutable material coordinates.
No model, wave, solver or picking code is generated. Original experiments and
core files are read-only; --check verifies the new header.
"""
import argparse
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'platform/3ds/relic_material_data.h'
N = 4


def height(x, y, u):
    def g(cx, cy, sx, sy):
        return math.exp(-.5 * (((x-cx)/sx)**2 + ((y-cy)/sy)**2))
    masses = 43*g(-35,-17,18,14)+40*g(28,-20,19,14)+42*g(34,18,19,15)+36*g(-24,24,20,15)
    return 8+math.sqrt(max(0.,1-u*u))*(19+masses-3*g(1,1,13,11))


def generate():
    text = (ROOT/'core/engine/relic_surface_data.h').read_text()
    def records(name):
        block = text.split(' '+name+'[', 1)[1].split('};', 1)[0]
        return [tuple(map(int, row.split(','))) for row in re.findall(r'\{([^{}]+)\}', block)]
    rest, control = records('rest'), records('faces')
    assert len(rest)==225 and len(control)==416
    # Invert the original outline at each XY, rather than linearly interpolating
    # radius across a polar triangle (which makes false spokes near its center).
    def radius(x,y):
        t = math.atan2(y/44, x/66)
        c = 1-.025*math.cos(4*t-.3)+.035*math.sin(2*t)+.035*math.cos(t+.7)+.015*math.cos(3*t+.4)
        return min(1., math.hypot(x/66,y/44)/c)
    samples = [(i,i,i,N,0,0) for i in range(225)]
    ids = {((i,N),):i for i in range(225)}
    faces=[]
    for k, face in enumerate(control):
        local={}
        for j in range(N+1):
            for i in range(N-j+1):
                w=(N-i-j,i,j)
                key=tuple(sorted((v,weight) for v,weight in zip(face,w) if weight))
                if key not in ids:
                    xyz=[sum(rest[v][axis]*weight/N for v,weight in key) for axis in range(3)]
                    # The vertical skirt is exactly control-surface subdivision.
                    # Its top rim remains Z=8, so it joins without a crack.
                    dz=0 if k>=352 else round(height(xyz[0]/128,xyz[1]/128,radius(xyz[0]/128,xyz[1]/128))*128-xyz[2])
                    # Rim chord is not the curved original outline: preserve the
                    # exact height of its 32 authoritative edges too.
                    if all(161<=v<225 for v,_ in key):dz=0
                    ids[key]=len(samples)
                    samples.append((*face,w[0],w[1],dz))
                local[i,j]=ids[key]
        for j in range(N):
            for i in range(N-j):
                faces.append((local[i,j],local[i+1,j],local[i,j+1]))
                if i+j<N-1:faces.append((local[i+1,j],local[i+1,j+1],local[i,j+1]))
    assert len(samples)==3393 and len(faces)==6656
    # Control knots are exact, including quantization; shared edges are deduped.
    assert all(s==(i,i,i,N,0,0) for i,s in enumerate(samples[:225]))
    parts=['// Generated by tools/generate_relic_material.py; renderer-only data.\n',
           '// Original four fused height masses; 32-sided control silhouette, not exact 112-sided AV rest.\n',
           '#pragma once\n#include "../../core/engine/relic_surface_data.h"\n',
           'namespace seance::platform::ui3ds::relic_material::data {\n',
           'struct Binding { uint16_t a,b,c; uint8_t wa,wb; int16_t dz; };\n',
           'inline constexpr unsigned subdivisions=4, vertex_count=3393, face_count=6656;\n',
           'inline constexpr uint32_t control_topology=3114473610u;\n']
    for typ,name,rows in [('Binding','bindings',samples),('relic::Face','faces',faces)]:
        parts.append(f'inline constexpr {typ} {name}[{len(rows)}] = {{\n')
        for start in range(0,len(rows),4):
            parts.append('    '+','.join('{'+','.join(map(str,row))+'}' for row in rows[start:start+4])+',\n')
        parts.append('};\n')
    parts+=['static_assert(control_topology==relic::surface_data::topology,"regenerate renderer bindings after topology changes");\n',
            '} // namespace seance::platform::ui3ds::relic_material::data\n']
    return ''.join(parts)


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    result=generate()
    if a.check:
        assert TARGET.read_text()==result, 'renderer binding drift'
        print('relic material: deterministic 3393v / 6656f, exact 225 control knots')
    else:
        print(result,end='')


if __name__=='__main__':main()
