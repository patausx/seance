#!/usr/bin/env python3
"""Bake the shared Seance Menu headings from unchanged Gossip Med Pixel (OFL 1.1).

Exact approved study raster: original 28 ppem, threshold 128, whole-label ink
crop. This extends Seance Menu separately; startup labels/data are untouched.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
OUT = ROOT / 'platform/3ds/menu_labels_data.h'
LABELS = ('patch table', 'go to', 'add module', 'empty',
          'osc', 'noise', 'fm', 'motor', 'play', 'gran', 'mic', 'filt', 'vca',
          'dly', 'rec', 'fold', 'bit', 'chor', 'strn', 'rev', 'ghost',
          'ring', 'tilt', 'strain', 'sigils', 'tempo', 'swing',
          'patches', 'unsaved changes', 'filter', 'echo', 'roll', 'samples',
          'modulation')
# Earlier shared/OSC masks and metrics remain byte-for-byte intact.
OSC_HERO_LABELS = ('sine', 'tri', 'saw', 'pulse', 'mute')
MOTOR_HERO_LABELS = ('mix',)  # saw/pulse reuse the existing 56ppem masks
BOUNCE_LABELS = ('bounce', 'ready', 'waiting', 'recording', 'take', 'partial', 'saved', 'replace chain', 'discard take', 'stop')
NAV_INK_LABELS = ('perform', 'sequencer')  # transient navigation titles only
MOUTH_HERO_LABELS = tuple('mouth-' + ch for ch in 'aeiou')
# Append new popup words: existing page/hero indices and bitmap offsets are stable.
POPUP_LABELS = ('exit',)
# INST appends masks only; all existing offsets/rasters stay unchanged.
INST_LABELS = ('inst', 'piano', 'violin', 'brass', 'flute', 'bass', 'drums',
               'kick', 'snare', 'hat', 'tom', 'openhat', 'cymbal')
INST_HERO_LABELS = tuple('inst-' + name for name in INST_LABELS[7:])
# Display rename only; append to preserve every existing mask/index/offset.
SWARM_LABELS = ('swarm',)


def masks():
    for text in LABELS + OSC_HERO_LABELS + MOTOR_HERO_LABELS + BOUNCE_LABELS + NAV_INK_LABELS + ('comp', 'patchbay', 'source', 'sigilbay') + tuple('abcdefgh0123456789') + ('mouth', 'vowel') + MOUTH_HERO_LABELS + POPUP_LABELS + ('arp', 'glitch') + INST_LABELS + INST_HERO_LABELS + SWARM_LABELS:
        hero = text in OSC_HERO_LABELS + MOTOR_HERO_LABELS + MOUTH_HERO_LABELS + INST_HERO_LABELS
        raster_text = text[5:] if text in INST_HERO_LABELS else text[-1] if text in MOUTH_HERO_LABELS else text
        face = ImageFont.truetype(str(FONT), 56 if hero else 28)
        box = list(face.getbbox(raster_text))
        if hero: box[1] = 8  # common top; preserve the 56ppem baseline/descenders
        mask = Image.new('L', (box[2] - box[0] + 4, box[3] - box[1] + 4))
        ImageDraw.Draw(mask).text((2 - box[0], 2 - box[1]), raster_text, font=face, fill=255)
        mask = mask.point(lambda p: 255 if p >= 128 else 0)
        assert mask.getbbox(), text
        ink = mask.getbbox()
        yield text, mask.crop((ink[0], 2, ink[2], ink[3]) if hero else ink)


def generate():
    data, labels = [], []
    for text, mask in masks():
        stride = (mask.width + 7) // 8
        assert 0 < mask.width < 256 and 0 < mask.height < 256
        labels.append((text, len(data), mask.width, mask.height))
        for y in range(mask.height):
            for byte in range(stride):
                data.append(sum(1 << (7 - bit) for bit in range(8)
                                if byte * 8 + bit < mask.width
                                and mask.getpixel((byte * 8 + bit, y))))
    assert len(data) < 65536
    lines = [
        '// Generated by tools/generate_menu_labels.py; do not hand-edit.',
        '// Seance Menu bitmap derivative, NOT the original Gossip font.',
        '// Copyright (c) 2025 Deborah Khodanovich; modifications 2026 Seance contributors.',
        '// SIL OFL 1.1; full license at assets/fonts/OFL.txt. Reserved original names not used.',
        '// Original OTF SHA256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
        '#pragma once', '#include <cstdint>',
        'namespace seance::platform::ui3ds::menu_labels {',
        'struct Label { const char* text; uint16_t offset; uint8_t width, height; };',
        'inline constexpr uint8_t bitmap[] = {',
    ]
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join(f'0x{x:02x}' for x in data[i:i + 20]) + ',')
    lines += ['};', 'inline constexpr Label labels[] = {']
    for text, offset, width, height in labels:
        lines.append(f'    {{"{text}", {offset}, {width}, {height}}},')
    lines += ['};', '} // namespace seance::platform::ui3ds::menu_labels', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        assert OUT.read_text() == output, 'stale shared Seance Menu bitmap data'
    else:
        OUT.write_text(output)
    print(f'Seance Menu: {len(LABELS)} unchanged 28ppem headings + '
          f'{len(OSC_HERO_LABELS)} OSC + {len(MOTOR_HERO_LABELS)} MOTOR baseline-aligned 56ppem words; '
          + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
