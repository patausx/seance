#!/usr/bin/env python3
"""Generate the bounded production relic rest mesh and integer control tables.

The four fused masses and outline equations are sampled from the protected
av_visual/model.h direction, not imported into production. No experiment is
written. Default output is stdout; --check compares the checked-in header.
"""
import argparse
import hashlib
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'core/engine/relic_surface_data.h'
SIDES, RINGS = 32, 6


def gaussian(x, y, cx, cy, sx, sy):
    return math.exp(-0.5 * (((x-cx)/sx)**2 + ((y-cy)/sy)**2))


def height(x, y, u):
    masses = (43*gaussian(x,y,-35,-17,18,14) + 40*gaussian(x,y,28,-20,19,14)
              + 42*gaussian(x,y,34,18,19,15) + 36*gaussian(x,y,-24,24,20,15))
    return 8 + math.sqrt(max(0, 1-u*u))*(19+masses-3*gaussian(x,y,1,1,13,11))


def mesh(sides=SIDES, rings=RINGS):
    points = [(0, 0, height(0,0,0))]
    radius = [0]
    for ring in range(1, rings+1):
        for a in range(sides):
            t, u = 2*math.pi*a/sides, math.sin(.5*math.pi*ring/rings)
            c = 1-.025*math.cos(4*t-.3)+.035*math.sin(2*t)+.035*math.cos(t+.7)+.015*math.cos(3*t+.4)
            x, y = 66*u*c*math.cos(t), 44*u*c*math.sin(t)
            points.append((x,y,height(x,y,u)))
            radius.append(u)
    def index(r, a):
        return 1+(r-1)*sides+a%sides
    faces = [(0,index(1,a),index(1,a+1)) for a in range(sides)]
    for ring in range(1,rings):
        for a in range(sides):
            p,q,s,t = index(ring,a),index(ring,a+1),index(ring+1,a),index(ring+1,a+1)
            faces.extend([(p,s,t),(p,t,q)])
    start = len(points)
    for a in range(sides):
        x,y,_ = points[index(rings,a)]
        points.append((x,y,0))
        radius.append(1)
    for a in range(sides):
        faces.extend([(index(rings,a),start+a,start+(a+1)%sides),
                      (index(rings,a),start+(a+1)%sides,index(rings,a+1))])
    return points, faces, radius


def generate():
    points, faces, radius = mesh()
    rest = [tuple(round(v*128) for v in p) for p in points]
    support = [0]*len(rest)
    area = []
    for a,b,c in faces[:352]:
        ar = (rest[b][0]-rest[a][0])*(rest[c][1]-rest[a][1])-(rest[b][1]-rest[a][1])*(rest[c][0]-rest[a][0])
        assert ar > 0
        area.append(ar)
        for i in (a,b,c):
            support[i] += ar
    sensors = []
    phase = lambda radians: round(radians/(2*math.pi)*(1<<32)) % (1<<32)
    for i,((x,y,_),u) in enumerate(zip(points,radius)):
        # Sensors observe the ACTUAL quantized rest, not a slightly different
        # floating mesh (important for nearly tangential residual bends).
        qx,qy,_ = rest[i]
        length = math.hypot(qx,qy)
        nx,ny = (qx/length,qy/length) if length else (1,0)
        sensors.append((round(nx*32767),round(ny*32767),
                        round(math.sqrt(max(0,1-u*u))*32767),
                        round(gaussian(x,y,-20,8,30,23)*32767),
                        phase(.064*x+.087*y),phase(-.053*x+.073*y+.9)))
    topology = int.from_bytes(hashlib.sha256(repr(faces).encode()).digest()[:4], 'little')
    parts = ['// Generated by tools/generate_relic_surface.py (stdout); do not edit.\n',
             '// Four fused av_visual masses, coarse polar approximation; no runtime transcendental math.\n',
             '// 225 vertices: center + six 32-point rings + floor skirt; 416 immutable triangles.\n',
             '#pragma once\n#include "relic_types.h"\nnamespace seance::relic::surface_data {\n',
             'struct Sensor { int16_t nx, ny; uint16_t cap, wave_weight; uint32_t phase1, phase2; };\n',
             f'inline constexpr uint32_t topology = {topology}u;\n',
             f'inline constexpr uint32_t phase_step1 = {phase(.72*.01)}u, phase_step2 = {phase(.49*.01)}u;\n']
    def array(typ, name, values, records=False):
        parts.append(f'inline constexpr {typ} {name}[{len(values)}] = {{\n')
        rendered = ['{'+','.join(str(v) for v in row)+'}' for row in values] if records else list(map(str,values))
        for i in range(0,len(rendered),4 if records else 12):
            parts.append('    '+','.join(rendered[i:i+(4 if records else 12)])+',\n')
        parts.append('};\n')
    array('Vertex','rest',rest,True)
    array('Face','faces',faces,True)
    array('int32_t','top_area',area)
    array('uint32_t','support',support)
    array('Sensor','sensors',sensors,True)
    array('int16_t','sine',[round(math.sin(2*math.pi*i/1024)*32767) for i in range(1024)])
    mass = sum(s*sensors[i][2] for i,s in enumerate(support))
    parts.append(f'inline constexpr uint64_t wave_mass = {mass}ull;\n')
    parts.append('static_assert(sizeof(rest)/sizeof(rest[0]) == SURFACE_VERTICES);\n')
    parts.append('static_assert(sizeof(faces)/sizeof(faces[0]) == SURFACE_FACES);\n')
    parts.append('} // namespace seance::relic::surface_data\n')
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if TARGET.read_text() != text:
            raise SystemExit('relic surface differs from generator')
        print('relic surface: deterministic data match')
    else:
        print(text, end='')


if __name__ == '__main__':
    main()
