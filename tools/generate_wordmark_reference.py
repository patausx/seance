#!/usr/bin/env python3
"""Generate a test-only independent English endpoint oracle from the approved mask.

The editable 86x26 pixel master and its existing PNG remain unchanged. Runtime
uses wordmark_morph_data.h; this bitset is only a native placement/coverage oracle.
No retired splash interior, texture, animation or renderer is retained.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image
from pixel_wordmark import native_mask

ROOT = Path(__file__).resolve().parents[1]
MASK = ROOT / 'assets/branding/gothic_wordmark_native_mask.png'
HEADER = ROOT / 'tools/wordmark_reference.h'
EXPECTED_SHA = '899c7ec5cdef4fc5bc8f6f5701baf3235ce49e7612302b8b9e068e553bedad99'
BBOX = (28, 64, 372, 168)


def generate():
    digest = hashlib.sha256(MASK.read_bytes()).hexdigest()
    assert digest == EXPECTED_SHA, 'approved native mask changed; review before regenerating'
    with Image.open(MASK) as image:
        mask = image.convert('L')
    assert mask.size == (400, 240) and mask.getbbox() == BBOX
    assert set(mask.tobytes()) == {0, 255}
    assert mask.tobytes() == native_mask().tobytes(), 'mask must match integer-only master'
    pixels = mask.crop(BBOX).tobytes()
    data = bytearray((len(pixels) + 7) // 8)
    for bit, value in enumerate(pixels):
        if value:
            data[bit // 8] |= 1 << (bit % 8)
    x, y, right, bottom = BBOX
    lines = ['// Generated by tools/generate_wordmark_reference.py; test-only English oracle.',
             '// Source: assets/branding/gothic_wordmark_native_mask.png',
             f'// PNG SHA-256: {digest}',
             '// Row-major bits, least-significant bit first; not a runtime splash asset.',
             '#pragma once', '#include <cstdint>', '',
             'namespace wordmark_reference {',
             f'inline constexpr int kX={x}, kY={y}, kWidth={right-x}, kHeight={bottom-y};',
             f'inline constexpr std::uint8_t kMask[{len(data)}]={{']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{byte:02x}' for byte in data[i:i+16]) + ',')
    lines += ['};', '} // namespace wordmark_reference', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        assert HEADER.read_text() == content, 'stale English reference; regenerate explicitly'
        print('English reference: independent native mask/master and committed bitset match')
    else:
        HEADER.write_text(content)
        print(HEADER.relative_to(ROOT))


if __name__ == '__main__':
    main()
