#!/usr/bin/env python3
"""Private legacy-editor titles; original Gossip28, threshold128, no shared atlas edits."""
import argparse
import hashlib
import re
from pathlib import Path
try:
    from PIL import Image, ImageDraw, ImageFont
except ModuleNotFoundError:
    Image = ImageDraw = ImageFont = None
from module_catalogue import kind_ids, same_members

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
META = ROOT / 'platform/3ds/picker_catalogue.inc'
OUT = ROOT / 'platform/3ds/module_heading_data.h'


def generate():
    if Image is None:
        from generate_scratch_resources import retained_heading
        return retained_heading()
    entries = re.findall(r'^PICKER_ENTRY\((\w+), "([^"]+)"', META.read_text(), re.M)
    kinds = kind_ids((ROOT / 'core/engine/unit.h').read_text())
    same_members([kind for kind, _ in entries], kinds, 'heading generator catalogue')
    face = ImageFont.truetype(str(FONT), 28)
    data, rows = [], []
    for kind, name in entries:
        # The finished FILTER instrument already uses its full name on top.
        if kind == 'Filter':
            name = 'filter'
        im = Image.new('L', (256, 80))
        ImageDraw.Draw(im).text((4, 50), name, font=face, fill=255, anchor='ls')
        im = im.point(lambda v: 255 if v >= 128 else 0)
        box = im.getbbox()
        assert box
        mask = im.crop(box)
        if name == 'swarm':
            # Private title pair spacing: close the s/w and r/m gaps by one
            # pixel each. Keep every original 28ppem ink pixel; no resizing,
            # glyph clipping, font modification or larger module frame.
            assert mask.size == (59, 12)
            removed = (10, 42)
            assert all(not mask.crop((x, 0, x+1, mask.height)).getbbox() for x in removed)
            tight = Image.new('L', (57, mask.height))
            kept = [x for x in range(mask.width) if x not in removed]
            for dst, src in enumerate(kept):
                tight.paste(mask.crop((src, 0, src+1, mask.height)), (dst, 0))
            assert sum(tight.tobytes()) == sum(mask.tobytes())
            mask = tight
        assert mask.width <= 57 and mask.height <= 25
        offset = len(data)
        for y in range(mask.height):
            for byte in range((mask.width + 7) // 8):
                data.append(sum(1 << (7 - bit) for bit in range(8)
                    if byte * 8 + bit < mask.width and mask.getpixel((byte * 8 + bit, y))))
        rows.append(f'    {{UnitKind::{kind}, "{name}", {offset}, {mask.width}, {mask.height}}},')
    assert len(data) < 65536
    lines = [
        '// Generated by tools/generate_module_heading.py; private editor derivative.',
        '// Copyright (c) 2025 Deborah Khodanovich; modifications 2026 Seance contributors.',
        '// SIL OFL 1.1; assets/fonts/OFL.txt. Original reserved font name not used for derivative.',
        '// Original OTF SHA256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
        '// Catalogue SHA256: ' + hashlib.sha256(META.read_bytes()).hexdigest(),
        '#pragma once', '#include "../../core/engine/unit.h"',
        'namespace seance::platform::ui3ds::module_heading_data {',
        'struct Label { UnitKind kind; const char* name; uint16_t offset; uint8_t width, height; };',
        'inline constexpr uint8_t bitmap[] = {',
    ]
    lines += ['    ' + ','.join(f'0x{v:02x}' for v in data[i:i+20]) + ',' for i in range(0, len(data), 20)]
    lines += ['};', 'inline constexpr Label labels[] = {', *rows, '};',
        'constexpr bool complete() {',
        '    for (int k=1; k<int(UnitKind::Count); ++k) {',
        '        int seen=0; for (const auto& label:labels) if (int(label.kind)==k) ++seen;',
        '        if (seen!=1) return false;',
        '    } return true;', '}',
        'static_assert(complete(), "all builtin editor titles have exact masks");',
        '} // namespace seance::platform::ui3ds::module_heading_data', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        assert OUT.read_text() == text, 'stale private module headings'
    else:
        OUT.write_text(text)
    print(str(text.count('{UnitKind::')) + ' private Gossip28 editor titles: ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
