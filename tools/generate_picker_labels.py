#!/usr/bin/env python3
"""Bake PRIVATE picker labels from unchanged Gossip-MedPixel.otf (SIL OFL).

Approved v9 raster: threshold128, crop to ink, retain baseline dy; 28ppem
rows fit156px and 40ppem titles fit248px (28 fallback). No shared font edits.
Metadata follows picker_catalogue.inc display order, never persisted IDs.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import textwrap
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
META = ROOT / 'platform/3ds/picker_catalogue.inc'
OUT = ROOT / 'platform/3ds/picker_catalogue_data.h'


def entries():
    result = []
    for line in META.read_text().splitlines():
        if not line.startswith('PICKER_ENTRY('):
            continue
        match = re.fullmatch(r'PICKER_ENTRY\((\w+), ("[^"]*"), ("[^"]*"), (\w+), ("[^"]*")\)', line)
        assert match, line
        kind, short, name, group, description = match.groups()
        result.append((kind, json.loads(short), json.loads(name), group, json.loads(description)))
    assert len(result) == len({e[0] for e in result})
    return result


def glyph(text, size):
    face = ImageFont.truetype(str(FONT), size)
    im = Image.new('L', (640, 100))
    ImageDraw.Draw(im).text((4, 70), text, font=face, fill=255, anchor='ls')
    im = im.point(lambda v: 255 if v >= 128 else 0)
    box = im.getbbox()
    assert box
    return im.crop(box), box[1] - 70


def fit(text, size, width):
    if glyph(text, size)[0].width <= width:
        return text
    while text and glyph(text + '...', size)[0].width > width:
        text = text[:-1]
    assert text
    return text.rstrip() + '...'


def generate():
    records = entries()
    data, labels, rows = [], [], {}
    def label(name, text, size, width):
        text = fit(text, size, width)
        mask, dy = glyph(text, size)
        offset = len(data)
        for y in range(mask.height):
            for b in range((mask.width + 7) // 8):
                data.append(sum(1 << (7 - k) for k in range(8)
                    if b * 8 + k < mask.width and mask.getpixel((b * 8 + k, y))))
        labels.append(f'inline constexpr Label {name} = {{{offset}, {mask.width}, {mask.height}, {dy}}};')
        return name
    # Keep raster offsets stable; only the entry table follows catalogue order.
    for kind, short, name, group, description in sorted(records, key=lambda e: (e[2], e[0])):
        row = label(kind + '_row', name, 28, 156)
        size = 40 if glyph(name, 40)[0].width <= 248 else 28
        title = label(kind + '_title', name, size, 248)
        desc = textwrap.wrap(description, 40, break_long_words=True, break_on_hyphens=False)
        assert len(desc) <= 2
        desc += [''] * (2 - len(desc))
        assert all(32 <= ord(ch) < 127 for ch in name + description)
        rows[kind] = '    {UnitKind::%s, %s, %s, Group::%s, {%s, %s}, %s, %s},' % (
            kind, json.dumps(short), json.dumps(name), group,
            json.dumps(desc[0]), json.dumps(desc[1]), row, title)
    label('empty_title', 'no modules', 28, 248)
    assert len(data) < 65536
    lines = [
        '// Generated by tools/generate_picker_labels.py; private picker derivative only.',
        '// Copyright (c) 2025 Deborah Khodanovich; modifications 2026 Seance contributors.',
        '// SIL OFL 1.1; assets/fonts/OFL.txt. Original reserved names not used for derivative.',
        '// Original OTF SHA256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
        '// Metadata SHA256: ' + hashlib.sha256(META.read_bytes()).hexdigest(),
        '#pragma once', '#include "../../core/engine/unit.h"',
        'namespace seance::platform::ui3ds::picker_catalogue {',
        'enum class Group : uint8_t { All, Sources, Tone, Time, Tools, User };',
        'inline constexpr const char* filters[] = {"all", "sources", "tone", "time", "tools", "user"};',
        'inline constexpr int filter_count = sizeof filters / sizeof filters[0];',
        'struct Label { uint16_t offset; uint8_t width, height; int8_t dy; };',
        'inline constexpr uint8_t bitmap[] = {',
    ]
    lines += ['    ' + ','.join('0x%02x' % x for x in data[i:i+20]) + ',' for i in range(0, len(data), 20)]
    lines += ['};', *labels,
        'struct Entry { UnitKind kind; const char* short_name; const char* name; Group group;',
        '    const char* description[2]; Label row, title; };',
        'inline constexpr Entry entries[] = {', *(rows[e[0]] for e in records), '};',
        'inline constexpr int count = sizeof entries / sizeof entries[0];',
        'static_assert(count == int(UnitKind::Count)-1, "every builtin needs picker metadata");',
        'constexpr bool complete() {',
        '    for (int k=1; k<int(UnitKind::Count); ++k) { int seen=0;',
        '        for (const auto& e:entries) if (int(e.kind)==k) ++seen;',
        '        if (seen!=1) return false; } return true;',
        '}', 'static_assert(complete(), "unique and complete builtin picker catalogue");',
        '} // namespace seance::platform::ui3ds::picker_catalogue', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        assert OUT.read_text() == output, 'stale private picker catalogue/font'
    else:
        OUT.write_text(output)
    print('private picker: %d entries, exact Gossip28/40 masks, %s' % (len(entries()), 'verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
