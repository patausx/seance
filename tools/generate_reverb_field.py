#!/usr/bin/env python3
"""Bake the approved REV membrane silhouette; data is NOT PCM or FFT.

Runtime deforms these two static heights using copied accepted parameters and
four measured tap envelopes. --check only compares, never modifies files.
"""
from pathlib import Path
import argparse
import math

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'platform/3ds/reverb_field_data.h'


def content():
    rows = []
    for row in range(19):
        v = row / 18
        values = []
        for col in range(33):
            u = col / 16 - 1
            envelope = max(0, 1-u*u)**1.4 * math.sin(math.pi*v)**.8
            broad = .5+.5*math.cos(2.4*math.pi*u+2*(v-.5))
            detail = .5+.5*math.cos(5*math.pi*u-3*v)
            values.append('{%d,%d}' % (round(255*envelope*(.22+.60*broad)), round(255*envelope*.18*detail)))
        rows.append('    {' + ','.join(values) + '},')
    return ('// Generated by tools/generate_reverb_field.py; static art, not audio data.\n'
            '#pragma once\n#include <cstdint>\n'
            'namespace seance::platform::ui3ds::reverb_field {\n'
            'constexpr int ROWS=19, COLS=33;\n'
            'struct Height { uint8_t broad, fine; };\n'
            'constexpr Height HEIGHT[ROWS][COLS] = {\n' + '\n'.join(rows) + '\n};\n'
            'static_assert(sizeof(HEIGHT)==1254,"fixed ROM artwork budget");\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = content()
    if args.check:
        assert DEST.read_text() == text, 'field ROM differs from generator'
    else:
        # Source generation is deliberate; never overwrite a different existing
        # table silently. Revise via a reviewed source change, not rerunning this.
        if DEST.exists():
            assert DEST.read_text() == text, 'refusing different existing table'
        else:
            DEST.write_text(text)
    print('rev field static ROM exact: 19 x 33 x 2 bytes')


if __name__ == '__main__':
    main()
