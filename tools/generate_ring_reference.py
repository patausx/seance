#!/usr/bin/env python3
"""Generate the approved Ring UI reference constants; never change the audio DSP.

The 32ms/250Hz/.75FS raised-cosine burst matches tools/ring_review.cpp.
--check verifies the committed UI constants against the current DSP frequency LUT.
"""
from pathlib import Path
import math
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'platform/3ds/ring_reference_data.h'


def generated():
    core = (ROOT / 'core/engine/units.cpp').read_text()
    match = re.search(r'RING_INC_LUT\[65\] = \{(.*?)\};', core, re.S)
    inc = [int(s) for s in re.findall(r'(\d+)u', match[1])]
    assert len(inc) == 65
    burst = []
    for i in range(1024):
        env = (.5 - .5 * math.cos(math.pi * i / 128) if i < 128
               else .5 + .5 * math.cos(math.pi * (i - 128) / 895))
        value = 24575 * env * math.sin(2 * math.pi * i / 128)
        burst.append(math.floor(value + .5) if value >= 0 else math.ceil(value - .5))
    def rows(values, suffix=''):
        return '\n'.join('    ' + ','.join(f'{v}{suffix}' for v in values[i:i+12]) + ','
                         for i in range(0, len(values), 12))
    return ('// Generated by tools/generate_ring_reference.py; UI-only, not audio tables.\n'
            '#pragma once\n#include <cstdint>\n\n'
            'namespace seance::platform::ui3ds::ring_reference::data {\n'
            'inline constexpr uint32_t INCREMENT[65] = {\n' + rows(inc, 'u') + '\n};\n'
            'inline constexpr int16_t BURST[1024] = {\n' + rows(burst) + '\n};\n}\n')


if __name__ == '__main__':
    text = generated()
    if '--check' in sys.argv:
        assert OUT.read_text() == text, 'Ring UI constants stale; regenerate explicitly'
        print('ring reference: burst + current 65-entry DSP LUT exact')
    else:
        OUT.write_text(text)
        print(OUT.relative_to(ROOT))
