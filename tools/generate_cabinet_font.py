#!/usr/bin/env python3
"""Bounded 22ppem cabinet ASCII; unchanged Gossip OTF, SIL OFL 1.1."""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont
from render_module_geometry_study import FONT as NATIVE
ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'assets/fonts/Gossip-MedPixel.otf'
OUT=ROOT/'platform/3ds/cabinet_font_data.h'

def generate():
    face=ImageFont.truetype(str(FONT),22)
    data=[]; metrics=[]; fallback=[]
    missing=Image.new('L',(80,80))
    ImageDraw.Draw(missing).text((30,40),'\u0378',font=face,anchor='ls',fill=255)
    missing=missing.point(lambda x:255 if x>=128 else 0)
    for code in range(32,127):
        ch=chr(code); im=Image.new('L',(80,80))
        ImageDraw.Draw(im).text((30,40),ch,font=face,anchor='ls',fill=255)
        im=im.point(lambda x:255 if x>=128 else 0)
        advance=round(face.getlength(ch)*64)
        if code!=32 and (not im.getbbox() or im.tobytes()==missing.tobytes()):
            # OTF has blank and .notdef ASCII entries. Preserve literal punctuation
            # with the existing native donor at 2x, not invisible/replacement boxes.
            im=Image.new('L',(80,80));draw=ImageDraw.Draw(im)
            for row,bits in enumerate(NATIVE[code-32]):
                for col in range(6):
                    if bits & (1<<(5-col)):
                        draw.rectangle((30+col*2,26+row*2,31+col*2,27+row*2),fill=255)
            advance=12*64;fallback.append(code)
        box=im.getbbox() or (30,40,30,40)
        assert code==32 or im.getbbox(),ch
        x,y,r,b=box; w,h=r-x,b-y; stride=(w+7)//8
        metrics.append((len(data),w,h,x-30,y-40,advance))
        for row in range(h):
            for col in range(stride):
                data.append(sum(1<<(7-bit) for bit in range(8) if col*8+bit<w and im.getpixel((x+col*8+bit,y+row))))
    assert len(data)<65536
    lines=['// Generated by tools/generate_cabinet_font.py; do not hand-edit.',
           '// Seance Cabinet bitmap derivative; copyright Deborah Khodanovich 2025.',
           '// Modifications 2026 Seance contributors; SIL OFL 1.1, assets/fonts/OFL.txt.',
           '// Original font unchanged: '+hashlib.sha256(FONT.read_bytes()).hexdigest(),
           '// Native 6x8 donor SHA256: '+hashlib.sha256((ROOT/'core/ui/font.cpp').read_bytes()).hexdigest(),
           '// Literal native-2x fallback ASCII: '+','.join(map(str,fallback)),
           '#pragma once','#include <cstdint>','namespace seance::platform::ui3ds::cabinet_font {',
           'struct Glyph { uint16_t offset; uint8_t width, height; int8_t x, y; uint16_t advance; };',
           'inline constexpr uint8_t bits[] = {']
    for i in range(0,len(data),20):lines.append('    '+','.join(str(v) for v in data[i:i+20])+',')
    lines+=['};','inline constexpr Glyph glyphs[] = {']
    for code,m in enumerate(metrics,32):lines.append('    {'+','.join(map(str,m))+'}, // ascii '+str(code))
    lines+=['};','} // namespace seance::platform::ui3ds::cabinet_font','']
    return '\n'.join(lines)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    p.add_argument('--replace',action='store_true',help='explicitly regenerate after backing up the data file');a=p.parse_args()
    text=generate()
    if a.check:assert OUT.read_text()==text,'stale cabinet font'
    else:
        assert a.replace or not OUT.exists(),'preserve existing data; review regeneration explicitly'
        OUT.write_text(text)
    print('cabinet font: 95 ASCII glyphs, 22ppem, exact threshold128; '+('verified' if a.check else 'generated'))
