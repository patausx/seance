#!/usr/bin/env python3
"""Offline binary32 coefficients for the selected relic source/filter/stereo FDN recipe."""
import argparse
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
DELAYS = (2473, 3167, 3761, 4481, 5233, 5801, 6521, 7103)


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0].hex() + 'f'


def generate():
    text = ['// Generated by tools/generate_relic_audio_tables.py; exact binary32 hex literals.\n',
            '// Selected Hann2048/pan256/four-pole filters/2.2s stereo FDN, no runtime trig.\n',
            '// Readonly shared across cards, never copied into each Audio allocation.\n',
            '#pragma once\nnamespace seance::relic::audio_tables {\n']

    def table(name, values):
        text.append(f'inline constexpr float {name}[{len(values)}] = {{\n')
        for i in range(0, len(values), 6):
            text.append('    ' + ', '.join(f32(x) for x in values[i:i + 6]) + ',\n')
        text.append('};\n')

    hann = [.5 - .5 * math.cos(2 * math.pi * i / 2048) for i in range(2049)]
    hann[0] = hann[-1] = 0
    table('hann', hann)
    table('pan_left', [math.cos(math.pi * .5 * i / 256) for i in range(257)])
    table('pan_right', [math.sin(math.pi * .5 * i / 256) for i in range(257)])
    table('filter_alpha', [1 - math.exp(-2 * math.pi * f / 32000) for f in (1800, 110, 430)])
    table('delay_gain', [math.pow(10, -3 * n / (32000 * 2.2)) for n in DELAYS])
    table('meter_alpha', [1 - math.exp(-2 * math.pi * f / 32000) for f in (115, 500)])
    text.append('} // namespace seance::relic::audio_tables\n')
    return ''.join(text)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    target = ROOT / 'core/engine/relic_audio_tables.h'
    content = generate()
    if a.check:
        assert target.read_text() == content, 'relic audio tables differ'
        print('relic audio tables: exact generated coefficients')
    else:
        target.write_text(content)
