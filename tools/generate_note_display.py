#!/usr/bin/env python3
"""Bake Seance Note, an OFL bitmap derivative of Gossip Med Pixel.
Original OTF is preserved verbatim. Device builds never require Pillow/FreeType.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT/'assets/fonts/Gossip-MedPixel.otf'
OUT = ROOT/'platform/3ds/note_display_data.h'


def generate():
    bits, metrics = [], []
    for small, chars, size in ((False, 'abcdefg0123456789', 56), (True, '0123456789r', 28)):
        f = ImageFont.truetype(FONT, size, layout_engine=ImageFont.Layout.BASIC)
        for char in chars:
            im = Image.new('L', (128,128))
            ImageDraw.Draw(im).text((16,80),char,font=f,anchor='ls',fill=255)
            im = im.point(lambda p:255 if p>=128 else 0)
            box=im.getbbox()
            assert box and 0<box[0]<box[2]<128 and 0<box[1]<box[3]<128
            mask=im.crop(box); stride=(mask.width+7)//8
            assert mask.width<=32 and mask.height<=50
            metrics.append((char,small,len(bits),mask.width,mask.height,box[1]-80))
            for y in range(mask.height):
                for b in range(stride):
                    bits.append(sum(1<<(7-k) for k in range(8) if b*8+k<mask.width and mask.getpixel((b*8+k,y))))
    out=['// Generated by tools/generate_note_display.py; do not hand-edit.',
         '// Seance Note bitmap derivative, NOT the original Gossip font.',
         '// Copyright (c) 2025 Deborah Khodanovich; modifications 2026 Seance contributors.',
         '// SIL OFL 1.1; full license at assets/fonts/OFL.txt. Reserved original names not used.',
         '// Original OTF SHA256: '+hashlib.sha256(FONT.read_bytes()).hexdigest(),
         '#pragma once', '#include <cstdint>',
         'namespace seance::platform::ui3ds::note_display {',
         'struct Glyph { char character; bool small; uint16_t offset; uint8_t width, height; int8_t top; };',
         'inline constexpr uint8_t bitmap[] = {']
    for i in range(0,len(bits),20): out.append('    '+','.join(f'0x{x:02x}' for x in bits[i:i+20])+',')
    out+=['};','inline constexpr Glyph glyphs[] = {']
    for c,s,o,w,h,t in metrics: out.append(f"    {{'{c}', {'true' if s else 'false'}, {o}, {w}, {h}, {t}}},")
    out+=['};','} // namespace seance::platform::ui3ds::note_display','']
    return '\n'.join(out)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args(); data=generate()
    if args.check:
        assert OUT.read_text()==data, 'stale note bitmap data'
    else: OUT.write_text(data)
    print('Seance Note: 28 baked glyphs, original outlines, native threshold128; '+('verified' if args.check else 'generated'))

if __name__=='__main__': main()
