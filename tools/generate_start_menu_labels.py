#!/usr/bin/env python3
"""Bake Seance Menu labels from unchanged Gossip Med Pixel, SIL OFL 1.1.

Exact approved concept raster: original 28 ppem outlines, threshold 128,
then crop to ink. No runtime font engine and no modifications to source fonts.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
OUT = ROOT / 'platform/3ds/start_menu_labels_data.h'
# Keep the original home labels/indices/bytes unchanged; append static editor labels.
LABELS = ('new patch', 'library', 'settings', 'themes',
          'pink', 'gray', 'old grimoire', 'black mass', 'custom', 'ring')


def masks():
    font = ImageFont.truetype(str(FONT), 28)
    for text in LABELS:
        box = font.getbbox(text)
        mask = Image.new('L', (max(1, box[2] - box[0] + 4),
                               max(1, box[3] - box[1] + 4)), 0)
        ImageDraw.Draw(mask).text((2 - box[0], 2 - box[1]), text, font=font, fill=255)
        mask = mask.point(lambda p: 255 if p >= 128 else 0)
        assert mask.getbbox()
        yield text, mask.crop(mask.getbbox())


def generate():
    data, labels = [], []
    for text, mask in masks():
        stride = (mask.width + 7) // 8
        labels.append((text, len(data), mask.width, mask.height))
        for y in range(mask.height):
            for b in range(stride):
                data.append(sum(1 << (7 - k) for k in range(8)
                                if b * 8 + k < mask.width and mask.getpixel((b * 8 + k, y))))
    lines = [
        '// Generated by tools/generate_start_menu_labels.py; do not hand-edit.',
        '// Seance Menu bitmap derivative, NOT the original Gossip font.',
        '// Copyright (c) 2025 Deborah Khodanovich; modifications 2026 Seance contributors.',
        '// SIL OFL 1.1; full license at assets/fonts/OFL.txt. Reserved original names not used.',
        '// Original OTF SHA256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
        '#pragma once', '#include <cstdint>',
        'namespace seance::platform::ui3ds::start_menu_labels {',
        'struct Label { uint16_t offset; uint8_t width, height; };',
        'inline constexpr uint8_t bitmap[] = {',
    ]
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join(f'0x{x:02x}' for x in data[i:i + 20]) + ',')
    lines += ['};', 'inline constexpr Label labels[] = {']
    for text, offset, width, height in labels:
        lines.append(f'    {{{offset}, {width}, {height}}}, // {text}')
    lines += ['};', '} // namespace seance::platform::ui3ds::start_menu_labels', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        assert OUT.read_text() == output, 'stale Seance Menu bitmap data'
    else:
        OUT.write_text(output)
    print(f'Seance Menu: {len(LABELS)} exact cropped 28ppem headings; ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
