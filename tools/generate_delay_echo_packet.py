#!/usr/bin/env python3
"""Build a fixed display-only packet LUT from the approved echo concept formula.

Not PCM or DSP: one normalization for the common 72ms pulse, 16 fractional
pixel phases, nine samples per column, always 0..1.6s across 280 pixels.
"""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'platform/3ds/delay_echo_model.h'


def pulse(t):
    if not 0 <= t <= 72:
        return 0.0
    u = t / 72
    return math.sin(6 * math.pi * u) * math.exp(-3 * u) * min(1, u * 24)


def table(span, columns):
    norm = max(abs(pulse(i / 16)) for i in range(72 * 16 + 1))
    rows = []
    for phase in range(16):
        cells = []
        for col in range(columns):
            values = [pulse((col + j / 32 - .5 - phase / 16) * span / 280) / norm
                      for j in range(33)] if span > 1600 else [
                          pulse((col + j / 8 - .5 - phase / 16) * span / 280) / norm for j in range(9)]
            cells.append('{%d,%d}' % (round(min(values) * 32767), round(max(values) * 32767)))
        rows.append('    {' + ','.join(cells) + '}')
    return ',\n'.join(rows)


def main():
    OUT.write_text('''// Generated by tools/generate_delay_echo_packet.py. Display model, NEVER PCM.
#pragma once
#include "../../core/audio/fixed.h"
namespace seance::platform::ui3ds::delay_echo_model {
constexpr int X0=24, X1=304, SPAN_FRAMES=51200, PACKET_FRAMES=2304;
inline int time_frames(q15 raw) {
    const unsigned v=raw<0?0:raw;
    return 32+((v*31967u)>>15); // existing legacy control_tick mapping
}
inline int onset_q4(int samples) {
    return (samples*((X1-X0)*16)+SPAN_FRAMES/2)/SPAN_FRAMES;
}
// Fractional onset phases; min/max of ONE fixed source sampled per pixel.
// Overlapping packets are overlaid, NOT summed or independently normalized.
constexpr int16_t PACKET[16][15][2]={
''' + table(1600, 15) + '\n};\n// Same 72ms source at labelled 6.4s scale; 33 subsamples per column.\n'
                   + 'constexpr int LONG_SPAN_FRAMES=204800;\nconstexpr int16_t LONG_PACKET[16][5][2]={\n'
                   + table(6400, 5) + '\n};\n}\n')


if __name__ == '__main__':
    main()
