#!/usr/bin/env python3
"""Local PENT seamless blood strip only; no source art rewrite, network or image model.

The immutable 128x16 period is repeated twice in a 256x16 PNG and packed in
previously transparent white-atlas rows192..207. Normal builds use the header.
This is a scoped implementation texture, not user/device artistic approval.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'platform/3ds/pent_flow_data.h'
ASSET = ROOT / 'assets/artwork/pent/pent_flow_strip_v1.png'
FACTS = ROOT / 'assets/artwork/pent/pent_flow_strip_v1.json'
PERIOD, HEIGHT, REPEATS = 128, 16, 2
PALETTE = ((187, 28, 49), (213, 40, 58), (237, 67, 85), (248, 144, 150))


def pixels():
    rows = []
    for y in range(HEIGHT):
        row = []
        for x in range(PERIOD):
            p = (0 if x == PERIOD-1 else x) * math.tau / PERIOD
            center = 7.5 + .55 * math.sin(p) + .3 * math.sin(2*p + .5)
            half = 2.2 + 1.2 * (.5 + .5 * math.cos(p)) + .35 * math.sin(3*p)
            distance = abs(y + .5 - center)
            if distance >= half + .7:
                row.append((0, 0, 0, 0))
                continue
            alpha = 96 if distance >= half else 204 if distance >= half-.5 else 255
            # A long connected film, asymmetric wet ridge and elongated glints;
            # no detached drop, cap, particle tile or animation frame.
            color = 0 if y+.5 > center+half*.28 else 1
            ridge = center-half+.8
            if abs(y+.5-ridge) < .7:
                color = 2
                if math.cos(p-.4) > .45:
                    color = 3
            row.append((*PALETTE[color], alpha))
        rows.append(row)
    assert all(all(row[x][3] > 0 for row in rows[6:10]) for x in range(PERIOD))
    # Continuous seam: x127->x0 is one ordinary neighbouring sample, not a cut to
    # a transparent cap. The central film exists for every longitudinal column.
    assert all(rows[y][0] == rows[y][-1] for y in range(HEIGHT))
    return rows


def png(raw):
    def chunk(kind, value):
        return struct.pack('>I', len(value)) + kind + value + struct.pack('>I', zlib.crc32(kind+value) & 0xffffffff)
    width = PERIOD * REPEATS
    scan = b''.join(b'\0' + raw[y*width*4:(y+1)*width*4] for y in range(HEIGHT))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, HEIGHT, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(scan, 9)) + chunk(b'IEND', b''))


def generate():
    rows = pixels()
    raw = b''.join(bytes(c) for row in rows for _ in range(REPEATS) for c in row)
    packed = [c[0] | c[1]<<8 | c[2]<<16 | c[3]<<24 for row in rows for c in row]
    lines = ['// Generated by tools/pent_flow_generate.py; local seamless connected blood film.',
             '// The old art/header/generator remain read-only. No ball or animated sprite.',
             '#pragma once', '#include <cstdint>',
             'namespace seance::platform::ui3ds::pent_flow_data {',
             'inline constexpr unsigned period=128, height=16, atlas_y=192, repeats=2;',
             'inline constexpr uint32_t pixels[] = {']
    lines += ['    '+','.join('0x%08xu' % c for c in packed[i:i+8])+',' for i in range(0, len(packed), 8)]
    lines += ['};', 'inline constexpr uint32_t pixel(unsigned x,unsigned y){',
              '    return x<256&&y<height?pixels[y*period+x%period]:0;', '}',
              'template<class Rect> inline void scanlines(Rect rect){',
              '    for(unsigned y=0;y<height;++y)for(unsigned x=0;x<256;){',
              '        const uint32_t c=pixel(x,y);unsigned end=x+1;',
              '        while(end<256&&pixel(end,y)==c)++end;',
              '        if(c>>24){rect(int(x),int(atlas_y+y),int(end-x),1,c);}x=end;',
              '    }', '}', '} // namespace seance::platform::ui3ds::pent_flow_data', '']
    header = '\n'.join(lines).encode()
    asset = png(raw)
    facts = dict(scope='local PENT implementation strip; not user/device approval',
                 period=[PERIOD, HEIGHT], texture_strip=[PERIOD*REPEATS, HEIGHT],
                 atlas_rect=[0, 192, 256, 16], rgba_bytes=len(raw),
                 gpu_allocation_bytes=0, gpu_total_bytes=524288,
                 palette_rgb=[list(c) for c in PALETTE],
                 rgba_sha256=hashlib.sha256(raw).hexdigest(),
                 png_sha256=hashlib.sha256(asset).hexdigest(),
                 header_sha256=hashlib.sha256(header).hexdigest(),
                 seam='all x127/x0 RGBA rows equal; two exact periods; center film nonempty everywhere',
                 runtime='scroll UV only, full five edges and shared vertex UVs; no recurring uploads')
    return {HEADER: header, ASSET: asset, FACTS: (json.dumps(facts, indent=2, sort_keys=True)+'\n').encode()}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    outputs = generate()
    if a.check:
        for path, data in outputs.items():
            assert path.read_bytes() == data, 'PENT flow derivative drift: '+str(path)
    else:
        assert not any(path.exists() for path in outputs), 'no overwrite; retain existing assets, use --check'
        for path, data in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open('xb') as stream:
                stream.write(data)
    print('pent flow: '+('verified' if a.check else 'created')+
          ' one seamless 128x16 period/two copies; unused atlas rows192..207; zero extra GPU allocation; old art intact')


if __name__ == '__main__':
    main()
