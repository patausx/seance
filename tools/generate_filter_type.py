#!/usr/bin/env python3
"""Private filter UI masks: current Gossip22/28/40, original/shared assets untouched."""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'assets/fonts/Gossip-MedPixel.otf'
OUT=ROOT/'platform/3ds/filter_type_data.h'
WORDS={22:('low pass','high pass','band pass','notch','off'),28:('filter',)}
CHARS='0123456789.'

def generate():
    data,labels,glyphs=[],[],[]
    def bake(text,size):
        face=ImageFont.truetype(str(FONT),size)
        image=Image.new('L',(256,100))
        ImageDraw.Draw(image).text((4,70),text,font=face,fill=255,anchor='ls')
        image=image.point(lambda value:255 if value>=128 else 0)
        box=image.getbbox();assert box,text
        mask=image.crop(box);width,height=mask.size
        assert width<128 and height<48
        result=(len(data),width,height,box[1]-70,box[0]-4,round(face.getlength(text)))
        for y in range(height):
            for x in range((width+7)//8):
                data.append(sum(1<<(7-bit) for bit in range(8) if x*8+bit<width and mask.getpixel((x*8+bit,y))))
        return result
    for size,words in WORDS.items():
        for word in words:labels.append((word,size,*bake(word,size)[:4]))
    for char in CHARS:glyphs.append((char,*bake(char,40)))
    assert len(data)<65536
    lines=['// Generated by tools/generate_filter_type.py; do not hand-edit.',
           '// Seance Filter bitmap derivative; copyright Deborah Khodanovich 2025.',
           '// Modifications 2026 Seance contributors; SIL OFL 1.1, assets/fonts/OFL.txt.',
           '// Original unchanged: '+hashlib.sha256(FONT.read_bytes()).hexdigest(),
           '#pragma once','#include <cstdint>',
           'namespace seance::platform::ui3ds::filter_type {',
           'struct Label { const char* text; uint8_t size; uint16_t offset; uint8_t width,height; int8_t top; };',
           'struct Glyph { char character; uint16_t offset; uint8_t width,height; int8_t top,left; uint8_t advance; };',
           'inline constexpr uint8_t bitmap[] = {']
    for i in range(0,len(data),20):lines.append('    '+','.join(map(str,data[i:i+20]))+',')
    lines+=['};','inline constexpr Label labels[] = {']
    for word,size,offset,w,h,top in labels:lines.append('    {"%s",%d,%d,%d,%d,%d},'%(word,size,offset,w,h,top))
    lines+=['};','inline constexpr Glyph glyphs[] = {']
    for char,offset,w,h,top,left,advance in glyphs:lines.append("    {'%s',%d,%d,%d,%d,%d,%d},"%(char,offset,w,h,top,left,advance))
    lines+=['};','} // namespace seance::platform::ui3ds::filter_type','']
    return '\n'.join(lines)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:assert OUT.read_text()==text,'stale filter masks'
    else:
        assert not OUT.exists(),'back up and explicitly remove existing generated file first'
        OUT.write_text(text)
    print('filter type: native masks '+('verified' if args.check else 'generated'))
