#!/usr/bin/env python3
"""Generate only compact C++ geometry/lighting data; never renders media.

Geometry, radii and lighting are defined by this generator.
Three subdivisions instead of four; retain the approved 30 fine-mesh tips by
moving their nearest coarse vertices onto the original directions. Profiles
and area-weighted normals are otherwise unchanged. Lighting uses a 64x64
full-sphere octahedral lookup (no per-face exp/pow in the runtime).
"""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'platform/3ds/nav_ferrofluid_data.h'


def dot(a, b):
    return sum(x*y for x, y in zip(a, b))


def unit(v):
    length = math.sqrt(dot(v, v))
    return tuple(x/length for x in v)


def mesh():
    p = (1+math.sqrt(5))/2
    vertices = [unit(v) for v in ((-1,p,0),(1,p,0),(-1,-p,0),(1,-p,0),
                (0,-1,p),(0,1,p),(0,-1,-p),(0,1,-p),(p,0,-1),(p,0,1),(-p,0,-1),(-p,0,1))]
    faces = [(0,11,5),(0,5,1),(0,1,7),(0,7,10),(0,10,11),(1,5,9),(5,11,4),
             (11,10,2),(10,7,6),(7,1,8),(3,9,4),(3,4,2),(3,2,6),(3,6,8),(3,8,9),
             (4,9,5),(2,4,11),(6,2,10),(8,6,7),(9,8,1)]
    coarse, coarse_faces = None, None
    for subdivision in range(4):
        edges, refined = {}, []
        def middle(a, b):
            key = tuple(sorted((a, b)))
            if key not in edges:
                edges[key] = len(vertices)
                vertices.append(unit(tuple(x+y for x, y in zip(vertices[a], vertices[b]))))
            return edges[key]
        for a, b, c in faces:
            ab, bc, ca = middle(a,b), middle(b,c), middle(c,a)
            refined.extend(((a,ab,ca),(b,bc,ab),(c,ca,bc),(ab,bc,ca)))
        faces = refined
        if subdivision == 2:
            coarse, coarse_faces = vertices.copy(), faces.copy()
    seeds, tips = [], []
    for i in range(30):
        y = 1-2*(i+.5)/30
        angle = i*math.pi*(3-math.sqrt(5))
        r = math.sqrt(1-y*y)
        desired = (r*math.cos(angle), y, r*math.sin(angle))
        seed = max(vertices, key=lambda v: dot(v, desired))
        tip = max(range(len(coarse)), key=lambda j: dot(coarse[j], seed))
        assert tip not in tips
        tips.append(tip)
        seeds.append(seed)
    for index, seed in zip(tips, seeds):
        coarse[index] = seed
    profiles = []
    for x, y, z in coarse:
        spike = 0.
        for index, seed in enumerate(seeds):
            distance = math.acos(max(-1., min(1., dot((x,y,z), seed))))
            if distance < .34:
                cone = (1-distance/.34)**1.55*(.83+.17*math.sin(index*2.3)**2)
                spike = max(spike, cone)
        bulk = 1+.065*math.sin(3*x+1)*math.cos(4*y-.2)+.038*math.sin(5*z+2*y)
        profiles.append((bulk, spike))
    # Convex blend of the original gentle profile and loud thin needles.
    # Narrowing only reduces each spike weight, so the unnarrowed endpoint is a
    # conservative bound for every blend/level/attack/rotation incl Q14 rounding.
    bound = max(max(65*bulk+35*spike, 48*bulk+58*spike)*1.045
                for bulk, spike in profiles)+.02
    assert bound < 112
    assert len(coarse) == 642 and len(coarse_faces) == 1280
    assert all(0 <= i < 642 for face in coarse_faces for i in face)
    return coarse, coarse_faces, profiles, tips, bound


def lighting():
    light = unit((-.45,.65,.70))
    half = unit((light[0],light[1],light[2]+1))
    violet = unit((.78,.1,.62))
    out = []
    for row in range(64):
        for col in range(64):
            x, y = col/63*2-1, row/63*2-1
            z = 1-abs(x)-abs(y)
            if z < 0:
                x, y = (1-abs(y))*(-1 if x < 0 else 1), (1-abs(x))*(-1 if y < 0 else 1)
            n = unit((x,y,z))
            diffuse = max(0.,dot(n,light))
            specular = max(0.,dot(n,half))**48
            rim = (1-max(0.,n[2]))**3
            rx, ry = 2*n[0]*n[2], 2*n[1]*n[2]
            softbox = math.exp(-((ry-.33)/.20)**2)*math.exp(-((rx+.30)/.78)**2)
            color = [max(0,min(255,round(base+diffuse*d+specular*s+rim*r+softbox*b)))
                     for base,d,s,r,b in ((13,21,195,43,79),(13,22,195,40,81),(18,28,202,57,91))]
            out.append((*color,round(max(0.,dot(n,violet))**17*255)))
    return out


def generate():
    vertices, faces, profiles, tips, bound = mesh()
    rows = ['// generated by tools/generate_nav_ferrofluid_data.py; no runtime generation.',
            '#pragma once', '#include <cstdint>',
            'namespace seance::platform::ui3ds::nav_ferrofluid::data {',
            'struct Vertex { int16_t x, y, z; uint16_t bulk, spike; }; // Q14 / Q15 spike',
            'struct Face { uint16_t a, b, c; };',
            'struct Light { uint8_t r, g, b, violet; };',
            'inline constexpr unsigned kVertexCount = 642, kFaceCount = 1280;',
            f'inline constexpr float kRadiusBound = {bound:.5f}f;',
            'inline constexpr Vertex kVertices[kVertexCount] = {']
    for v, (bulk, spike) in zip(vertices, profiles):
        values = [*(round(a*16384) for a in v), round(bulk*16384), round(spike*32768)]
        rows.append('    {'+','.join(map(str,values))+'},')
    rows += ['};', 'inline constexpr Face kFaces[kFaceCount] = {']
    rows += ['    {'+','.join(map(str,face))+'},' for face in faces]
    rows += ['};', 'inline constexpr uint16_t kTips[30] = {'+','.join(map(str,tips))+'};',
             'inline constexpr Light kLight[64*64] = {']
    shades = lighting()
    for i in range(0,len(shades),8):
        rows.append('    '+','.join('{'+','.join(map(str,shade))+'}' for shade in shades[i:i+8])+',')
    tone = [round(max(0.,min(1.,(luminance-12)/175))**.72*7) for luminance in range(256)]
    rows += ['};', 'inline constexpr uint8_t kTone[256] = {']
    rows += ['    '+','.join(map(str,tone[i:i+32]))+',' for i in range(0,256,32)]
    rows += ['};', 'static_assert(sizeof(Vertex) == 10 && sizeof(Face) == 6 && sizeof(Light) == 4);',
             'inline constexpr unsigned kStorageBytes = sizeof(kVertices) + sizeof(kFaces) + sizeof(kLight) + sizeof(kTone) + sizeof(kTips);',
             'static_assert(kStorageBytes <= 31*1024, "bounded read-only ferrofluid data");',
             'static_assert(kRadiusBound < 112, "rotation stays inside the padded 240px ROI");',
             '} // namespace seance::platform::ui3ds::nav_ferrofluid::data', '']
    return '\n'.join(rows)


if __name__ == '__main__':
    OUT.write_text(generate())
    print(f'{OUT.relative_to(ROOT)}: 642 vertices / 1280 faces / 30 original tips / 64x64 lighting')
