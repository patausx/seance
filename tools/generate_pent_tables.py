#!/usr/bin/env python3
"""Deterministic PENT integer tables; no generation/libm work on the audio thread."""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'core/engine/pent_tables.h'


def rounded(x):
    return int(math.floor(x + .5)) if x >= 0 else -int(math.floor(-x + .5))


def table(name, kind, values, per_line=12):
    text = f'static constexpr {kind} {name}[{len(values)}] = {{\n'
    for i in range(0, len(values), per_line):
        text += '    ' + ','.join(map(str, values[i:i + per_line])) + ',\n'
    return text + '};\n'


def generate():
    out = '// Generated by python3 -B tools/generate_pent_tables.py; do not edit.\n'
    out += '// PENT 2x integer synthesis: immutable, no runtime libm initialization.\n'
    out += '#pragma once\n#include <cstdint>\nnamespace seance { namespace pent_tables {\n'
    out += table('SINE', 'int16_t', [rounded(32767 * math.sin(2 * math.pi * i / 2048)) for i in range(2049)])
    # Positive half only, odd extension at runtime. 65 drive rows, 257 sine knots.
    out += table('SHAPE', 'uint16_t', [rounded(32767 * math.tanh((1 + 2.5 * d / 64) * x / 256) /
                 math.tanh(1 + 2.5 * d / 64)) for d in range(65) for x in range(257)])
    out += table('EXP2_Q24', 'uint32_t', [rounded(2 ** (i / 256) * (1 << 24)) for i in range(257)])
    out += table('ROOT_MILLIHZ', 'uint32_t', [rounded(440000 * 2 ** ((i - 69) / 12)) for i in range(121)])
    out += table('INITIAL_PHASE', 'uint32_t', [rounded(x / (2 * math.pi) * (1 << 32)) for x in (.17, 1.31, 2.47, 3.53, 5.11)])
    out += table('DRIFT_PHASE', 'uint32_t', [rounded(1.1 * i / (2 * math.pi) * (1 << 32)) for i in range(5)])
    anchors = [(1,4), (1,2), (1,1), (5,4), (3,2), (7,4), (2,1), (3,1), (4,1)]
    out += table('RATIO_RAW', 'int16_t', [rounded((math.log2(n / d) + 2) * 32767 / 4) for n,d in anchors])
    out += table('RATIO_Q16', 'uint32_t', [rounded(n / d * 65536) for n,d in anchors])
    out += table('VOICE_GAIN_Q16', 'int32_t', [rounded(.10 * x * 65536) for x in (1,.90,.85,.78,.72)])
    for name, side in [('PAN_LEFT', -1), ('PAN_RIGHT', 1)]:
        out += table(name, 'int32_t', [rounded(math.sqrt((1 + side * pan) * .5) * 32768) for pan in (0,.76,.47,-.47,-.76)])
    coefficients = []
    for k in range(47):
        t = k - 23
        sinc = 2 * 14000 / 64000 if t == 0 else math.sin(2 * math.pi * 14000 / 64000 * t) / (math.pi * t)
        window = .42 - .5 * math.cos(2 * math.pi * k / 46) + .08 * math.cos(4 * math.pi * k / 46)
        coefficients.append(sinc * window)
    dc = sum(coefficients)
    q = [rounded(x / dc * 32768) for x in coefficients]
    q[23] += 32768 - sum(q) # exact fixed DC calibration, not audio normalization
    out += table('FIR_Q15', 'int32_t', q)
    out += 'static constexpr uint32_t BOND_TURNS = ' + str(rounded(1.25 / (2 * math.pi) * (1 << 32))) + 'u;\n'
    out += 'static constexpr uint32_t MAX_INCREMENT = 805306368u; // 12000Hz at 64000Hz\n'
    out += 'static constexpr uint32_t FIR_L1_Q15 = ' + str(sum(map(abs, q))) + 'u;\n'
    out += '} } // namespace seance::pent_tables\n'
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if TARGET.read_text() != content:
            raise SystemExit('pent tables differ; regenerate explicitly')
        print('pent tables: exact')
    else:
        TARGET.write_text(content)
        print(TARGET)


if __name__ == '__main__':
    main()
