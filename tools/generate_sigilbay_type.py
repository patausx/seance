#!/usr/bin/env python3
"""Bake Seance Cable, a private OFL Gossip-derived sigilbay title alphabet.

No runtime font loading or changes to existing shared/menu/startup masks.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
OUT = ROOT / 'platform/3ds/sigilbay_type_data.h'
CHARS = 'abcdefghijklmnopqrstuvwxyz0123456789-+/%._:()?'


def generate():
    bits, metrics = [], []
    for small, size in ((False, 28), (True, 22)):
        face = ImageFont.truetype(str(FONT), size, layout_engine=ImageFont.Layout.BASIC)
        for char in CHARS:
            image = Image.new('L', (96, 96))
            ImageDraw.Draw(image).text((16, 60), char, font=face, anchor='ls', fill=255)
            image = image.point(lambda p: 255 if p >= 128 else 0)
            box = image.getbbox()
            assert box and 0 < box[0] < box[2] < 96 and 0 < box[1] < box[3] < 96
            mask = image.crop(box)
            metrics.append((char, small, len(bits), mask.width, mask.height, box[1] - 60))
            for y in range(mask.height):
                for byte in range((mask.width + 7) // 8):
                    bits.append(sum(1 << (7 - k) for k in range(8)
                                    if byte * 8 + k < mask.width and mask.getpixel((byte * 8 + k, y))))
    assert len(bits) < 65536
    lines = ['// Generated by tools/generate_sigilbay_type.py; do not hand-edit.',
             '// Seance Cable bitmap derivative, NOT the original Gossip font.',
             '// Copyright (c) 2025 Deborah Khodanovich; modifications 2026 Seance contributors.',
             '// SIL OFL 1.1; full license at assets/fonts/OFL.txt. Reserved original names not used.',
             '// Original OTF SHA256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
             '#pragma once', '#include <cstdint>',
             'namespace seance::platform::ui3ds::sigilbay_type {',
             'struct Glyph { char character; bool small; uint16_t offset; uint8_t width, height; int8_t top; };',
             'inline constexpr uint8_t bitmap[] = {']
    for i in range(0, len(bits), 20):
        lines.append('    ' + ','.join(f'0x{x:02x}' for x in bits[i:i + 20]) + ',')
    lines += ['};', 'inline constexpr Glyph glyphs[] = {']
    for char, small, offset, w, h, top in metrics:
        lines.append(f"    {{'{char}', {'true' if small else 'false'}, {offset}, {w}, {h}, {top}}},")
    lines += ['};', '} // namespace seance::platform::ui3ds::sigilbay_type', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = generate()
    if args.check:
        assert OUT.read_text() == data, 'stale sigilbay title data'
    else:
        OUT.write_text(data)
    print('seance cable: private 28/22ppem titles ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
