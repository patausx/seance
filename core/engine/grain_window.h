inline int16_t hann(uint32_t age, uint32_t length, uint32_t step) {
    if (length < 2 || age >= length) return 0;
    const uint32_t end = length - 1 - age;
    const uint32_t mirrored = age < end ? age : end;
    const uint64_t phase = uint64_t(mirrored) * step;
    const uint32_t index = uint32_t(phase >> 22);
    if (index >= 256) return 32767;
    const uint32_t fraction = uint32_t(phase) & ((1u << 22) - 1);
    return int16_t(hann_half[index] +
        ((uint32_t(hann_half[index + 1] - hann_half[index]) * fraction) >> 22));
}
