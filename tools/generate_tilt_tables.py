#!/usr/bin/env python3
"""Offline Tilt coefficient tables; no runtime transcendentals. Creates or verifies identical data."""
import math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def table(name,values):
 return f'inline constexpr uint32_t {name}[{len(values)}] = {{\n'+''.join('    '+','.join(str(v)+'u' for v in values[i:i+8])+',\n' for i in range(0,len(values),8))+'};\n'
def main():
 k=[round(math.tan(math.pi*125*2**(6*i/256)/32000)*(1<<28)) for i in range(257)]
 gain=[round(10**((-12+24*i/512)/20)*(1<<24)) for i in range(513)]
 text='// Generated by tools/generate_tilt_tables.py. Q28 prewarped pole / Q24 gain.\n#pragma once\n#include <cstdint>\nnamespace seance::tilt_extended {\n'+table('PIVOT_Q28',k)+table('GAIN_Q24',gain)+'}\n'
 path=ROOT/'core/engine/tilt_extended_data.h'
 if path.exists():assert path.read_text()==text,'refuse to overwrite changed table'
 else:path.write_text(text)
 print(path)
if __name__=='__main__':main()
