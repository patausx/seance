#!/usr/bin/env python3
"""Generate the approved Strain UI test burst, not an audio DSP table.

Exact source of tools/strain_review.cpp: .75fs/250hz, 2ms raised-cosine
attack + 14ms release. The runtime supplies the following 16ms silence.
--check verifies constants without changing any file.
"""
from pathlib import Path
import math
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'platform/3ds/strain_reference_data.h'


def generated():
    burst = []
    for i in range(512):
        env = (.5-.5*math.cos(math.pi*i/64) if i < 64
               else .5+.5*math.cos(math.pi*(i-64)/447))
        value = 24575*env*math.sin(2*math.pi*i/128)
        burst.append(math.floor(value+.5) if value >= 0 else math.ceil(value-.5))
    rows = '\n'.join('    '+','.join(map(str, burst[i:i+12]))+',' for i in range(0, 512, 12))
    return ('// Generated by tools/generate_strain_reference.py; UI-only test source.\n'
            '#pragma once\n#include <cstdint>\n\n'
            'namespace seance::platform::ui3ds::strain_reference::data {\n'
            'inline constexpr int16_t BURST[512] = {\n'+rows+'\n};\n}\n')


if __name__ == '__main__':
    text = generated()
    if '--check' in sys.argv:
        assert OUT.read_text() == text, 'Strain UI burst stale; regenerate explicitly'
        print('strain reference: approved 512-sample burst constants exact; next 512 silent')
    else:
        OUT.write_text(text)
        print(OUT.relative_to(ROOT))
