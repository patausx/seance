#!/usr/bin/env python3
"""Private PLAY editor bitmap derivative; original font and shared atlases untouched."""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
OUT = ROOT / 'platform/3ds/play_editor_type_data.h'
WORDS = {22: ('normal','stretch','tape','scratch','hold','config'),
         28: ('play','config','trim','slices','loop','fades','zoom','history','seq scrub','auto cuts','save copy','detach raw','crop copy')}
CHARS = '0123456789abcdefg#.-+'

def generate():
    data, labels, glyphs = [], [], []
    def bake(text,size):
        f=ImageFont.truetype(str(FONT),size)
        im=Image.new('L',(256,100))
        d=ImageDraw.Draw(im)
        d.text((4,70),text,font=f,fill=255,anchor='ls')
        # Original face has a blank sharp. Explicit native geometric fallback,
        # not a silently missing note identity (same principle as note_display).
        if text=='#':
            h=14 if size==40 else 10; w=10 if size==40 else 8; top=70-h-2
            d.rectangle((6,top,6,top+h-1),fill=255)
            d.rectangle((4+w-3,top,4+w-3,top+h-1),fill=255)
            d.rectangle((4,top+3,4+w-1,top+4),fill=255)
            d.rectangle((4,top+h-5,4+w-1,top+h-4),fill=255)
        im=im.point(lambda v:255 if v>=128 else 0)
        box=im.getbbox(); assert box,text
        mask=im.crop(box); width,height=mask.size
        assert width<128 and height<48
        result=(len(data),width,height,box[1]-70,box[0]-4,width+3 if text=='#' else round(f.getlength(text)))
        for y in range(height):
            for x in range((width+7)//8):
                data.append(sum(1<<(7-bit) for bit in range(8) if x*8+bit<width and mask.getpixel((x*8+bit,y))))
        return result
    for size,words in WORDS.items():
        for word in words:labels.append((word,size,*bake(word,size)[:4]))
    for size in (28,40):
        for char in CHARS:glyphs.append((char,size,*bake(char,size)))
    assert len(data)<65536
    lines=['// Generated by tools/generate_play_editor_type.py; do not hand-edit.',
           '// Seance Play bitmap derivative; copyright Deborah Khodanovich 2025.',
           '// Modifications 2026 Seance contributors; SIL OFL 1.1, assets/fonts/OFL.txt.',
           '// Original unchanged: '+hashlib.sha256(FONT.read_bytes()).hexdigest(),
           '#pragma once','#include <cstdint>',
           'namespace seance::platform::ui3ds::play_editor_type {',
           'struct Label { const char* text; uint8_t size; uint16_t offset; uint8_t width,height; int8_t top; };',
           'struct Glyph { char character; uint8_t size; uint16_t offset; uint8_t width,height; int8_t top,left; uint8_t advance; };',
           'inline constexpr uint8_t bitmap[] = {']
    for i in range(0,len(data),20):lines.append('    '+','.join(map(str,data[i:i+20]))+',')
    lines+=['};','inline constexpr Label labels[] = {']
    for word,size,offset,w,h,top in labels:lines.append('    {"%s",%d,%d,%d,%d,%d},'%(word,size,offset,w,h,top))
    lines+=['};','inline constexpr Glyph glyphs[] = {']
    for char,size,offset,w,h,top,left,adv in glyphs:lines.append("    {'%s',%d,%d,%d,%d,%d,%d,%d},"%(char,size,offset,w,h,top,left,adv))
    lines+=['};','} // namespace seance::platform::ui3ds::play_editor_type','']
    return '\n'.join(lines)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    text=generate()
    if a.check:assert OUT.read_text()==text,'stale PLAY masks'
    else:
        assert not OUT.exists(),'back up and explicitly remove existing generated file first'
        OUT.write_text(text)
    print('play editor type: native labels/glyphs '+('verified' if a.check else 'generated'))
