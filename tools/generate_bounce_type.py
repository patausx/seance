#!/usr/bin/env python3
"""Bake the approved bounce ribbon words at native size; no runtime font loader."""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/Gossip-MedPixel.otf'
OUT = ROOT / 'platform/3ds/bounce_type_data.h'
LABELS = {
    22: ['mix', *map(str, range(1, 9)), 'listen', 'stop listening', 'save wav',
         'wav saved', 'use in chain', 'record again', 'take ready', 'listening',
         'partial take', 'use chain', 'replace', 'release take', 'cancel'],
    28: ['1', '2', '4', '8', 'record', 'stop early', 'cancel', 'use in chain',
         'record again?'],
    40: list(map(str, range(9))),
}


def generate():
    data, labels = [], []
    for size, words in LABELS.items():
        face = ImageFont.truetype(str(FONT), size)
        for word in words:
            # Same baseline anchor, tight ink-left crop and threshold as the study.
            im = Image.new('L', (640, 100))
            ImageDraw.Draw(im).text((4, 70), word, font=face, fill=255, anchor='ls')
            im = im.point(lambda v: 255 if v >= 128 else 0)
            box = im.getbbox()
            assert box, word
            mask = im.crop(box)
            width, height = mask.size
            assert width <= 184 and height <= 42
            labels.append((word, size, len(data), width, height, box[1] - 70))
            for y in range(height):
                for x in range((width + 7) // 8):
                    data.append(sum(1 << (7-bit) for bit in range(8)
                                    if x*8+bit < width and mask.getpixel((x*8+bit, y))))
    assert len(data) < 65536
    lines = ['// Generated by tools/generate_bounce_type.py; do not hand-edit.',
             '// Seance Bounce bitmap derivative; copyright Deborah Khodanovich 2025.',
             '// Modifications 2026 Seance contributors; SIL OFL 1.1, assets/fonts/OFL.txt.',
             '// Original font unchanged: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
             '#pragma once', '#include <cstdint>',
             'namespace seance::platform::ui3ds::bounce_type {',
             'struct Label { const char* text; uint8_t size; uint16_t offset; uint8_t width, height; int8_t top; };',
             'inline constexpr uint8_t bitmap[] = {']
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join(map(str, data[i:i+20])) + ',')
    lines += ['};', 'inline constexpr Label labels[] = {']
    for word, size, offset, width, height, top in labels:
        lines.append('    {"%s",%d,%d,%d,%d,%d},' % (word, size, offset, width, height, top))
    lines += ['};', '} // namespace seance::platform::ui3ds::bounce_type', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        assert OUT.read_text() == text, 'stale bounce type masks'
    else:
        assert not OUT.exists(), 'back up and explicitly remove existing generated file first'
        OUT.write_text(text)
    print('bounce type: 40 labels; original 22/28/40ppem masks ' + ('verified' if args.check else 'generated'))
