#!/usr/bin/env python3
"""Lossless conversion of the two approved PENT sheets. No art generation/API.

Two ordered RGBA scanline streams per frame retain the exact source-over law,
white scaffold, ten wet drops, and red particle underlay. Runtime uses two cached
256x256 nearest textures (524288 bytes total), never thousands of GPU pixels.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'platform/3ds/pent_visual_data.h'
SOURCES = [('assets/artwork/pent/pent-glow-particles-v1.png', 200),
           ('assets/artwork/pent/pent-liquid-blood-v1.png', 192)]

def generate():
    palette = [0]
    indices = {0: 0}
    streams, heights, offsets, counts = [], [], [], []
    provenance = []
    for name, height in SOURCES:
        path = ROOT / name
        meta = json.loads(Path(str(path)+'.frames.json').read_text())
        assert meta['frames'] == 24 and meta['scale'] == 1 and meta['columns'] == 6
        raw = subprocess.run(['ffmpeg','-v','error','-threads','1','-i',str(path),
                              '-threads','1','-f','rawvideo','-pix_fmt','rgba','pipe:1'],
                             capture_output=True, check=True, timeout=40).stdout
        assert len(raw) == 1536*height*4*4
        provenance.append((name, hashlib.sha256(path.read_bytes()).hexdigest()))
        for frame in range(24):
            offsets.append(len(streams))
            rectangles = []
            previous = {}
            for y in range(height):
                row = []
                at = ((frame//6*height+y)*1536+frame%6*256)*4
                for x in range(256):
                    r,g,b,a = raw[at+x*4:at+x*4+4]
                    color = r | g<<8 | b<<16 | a<<24 if a else 0
                    if color not in indices:
                        indices[color] = len(palette); palette.append(color)
                    row.append(indices[color])
                x = 0
                current = {}
                while x < 256:
                    end = x+1
                    while end < 256 and row[end] == row[x]: end += 1
                    if row[x]:
                        key = (x, end-x, row[x])
                        if key in previous:
                            index = previous[key]
                            rectangles[index][1] += 1
                        else:
                            index = len(rectangles)
                            rectangles.append([x | y<<8 | (end-x-1)<<16 | row[x]<<24, 1])
                        current[key] = index
                    x = end
                previous = current
            streams.extend(r for r,h in rectangles)
            heights.extend(h for r,h in rectangles)
            counts.append(len(rectangles))
    offsets.append(len(streams))
    assert len(palette) <= 256
    lines = ['// Generated by tools/generate_pent_visual.py; exact approved local assets.',
             '// No generated art, RNG or DSP. FX first at (112,24); liquid at (112,32).']
    lines += ['// '+name+' sha256 '+digest for name,digest in provenance]
    lines += ['#pragma once', '#include <cstdint>',
              'namespace seance::platform::ui3ds::pent_visual_data {',
              'inline constexpr uint32_t colors[] = {']
    lines += ['    '+','.join('0x%08xu'%c for c in palette[i:i+8])+',' for i in range(0,len(palette),8)]
    lines += ['};','inline constexpr uint32_t offsets[] = {',
              '    '+','.join(str(x) for x in offsets), '};',
              'inline constexpr uint32_t runs[] = {']
    lines += ['    '+','.join('0x%08xu'%c for c in streams[i:i+12])+',' for i in range(0,len(streams),12)]
    lines += ['};', 'inline constexpr uint8_t heights[] = {']
    lines += ['    '+','.join(str(c) for c in heights[i:i+32])+',' for i in range(0,len(heights),32)]
    lines += ['};', 'inline constexpr uint8_t ring_x[] = {',
              '    '+','.join(str(math.isqrt(92*92-y*y)) for y in range(-92,93)), '};',
              'inline constexpr unsigned frames=24, width=256;',
              'inline constexpr unsigned max_runs='+str(max(counts))+';',
              '} // namespace seance::platform::ui3ds::pent_visual_data', '']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    text=generate()
    if a.check: assert OUT.read_text()==text, 'PENT approved atlas drift'
    else: OUT.write_text(text)
    print('pent: exact 2 x 24 scanline resources '+('verified' if a.check else 'converted'))
if __name__=='__main__':main()
