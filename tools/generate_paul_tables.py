#!/usr/bin/env python3
"""Original offline PAUL coefficients; no upstream code or FFT dependencies."""
import math
from pathlib import Path

def generate():
    parts = ['// Generated by tools/generate_paul_tables.py; original mathematical coefficients.\n#pragma once\n#include <cstdint>\nnamespace seance { namespace paul_tables {\n']
    def table(typ, name, values):
        parts.append(f'static constexpr {typ} {name}[{len(values)}] = {{\n')
        for i in range(0, len(values), 12):
            parts.append('    ' + ','.join(map(str, values[i:i+12])) + ',\n')
        parts.append('};\n')
    table('int32_t', 'cosine', [round(math.cos(2*math.pi*i/8192)*(1<<30)) for i in range(8192)])
    table('uint32_t', 'exp2', [round(2**(i/256)*(1<<16)) for i in range(257)])
    for n in (2048,4096,8192):
        w = [round((.5-.5*math.cos(2*math.pi*i/(n-1)))*(1<<16)) for i in range(n)]
        table('uint32_t', f'hann{n}', w)
        parts.append(f'static constexpr uint32_t sum{n} = {sum(w)}u;\n')
        # Exact reciprocal of the QUANTIZED squared Hann pair, Q30.
        table('uint32_t', f'norm{n}', [round((1<<62)/(w[i]**2+w[i+n//2]**2)) for i in range(n//2)])
    parts.append('} } // namespace seance::paul_tables\n')
    return ''.join(parts)

if __name__ == '__main__':
    import argparse
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    target = Path(__file__).resolve().parents[1] / 'core/engine/paul_tables.h'
    text = generate()
    if a.check:
        assert target.read_text() == text, 'PAUL tables differ from generator'
        print('paul tables: original coefficients match')
    else:
        target.write_text(text)
